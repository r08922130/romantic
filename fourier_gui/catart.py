"""
catart.py - the cats, traced from photos, each as ONE closed curve
==================================================================

    path, labels, parts = cat_stroke("box")        (or "lying", "tabby", "sitting")

The shapes below are in photo pixels (the photos themselves are not part of
the project). They were traced by hand; the edges between the orange and the
white fur were then measured with OpenCV, and the outlines moved onto the
measured edge. This file needs no image library. Every shape is a loop; a
line (a whisker, a stripe) is a loop that goes along it and comes back. The
loops are joined by the shortest links (a minimum spanning tree): the pen
goes over a link to the next loop, round it, and back over the same link. So
the whole cat is a single closed path, and ONE Fourier series draws it.

parts: label -> {"colour", "line", "fill", "width"}, in painting order (the
first one is at the back). The links have the label "link".
"""
import math

